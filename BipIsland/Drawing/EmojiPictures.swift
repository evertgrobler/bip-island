    /// An emoji picture for this id, sized to fit the ~220 box. Longer rows shrink.
    static func make(picture id: String) -> SKNode? {
        guard let icons = icons[id] else { return nil }
        let label = SKLabelNode(fontNamed: "AppleColorEmoji")
        label.text = icons
        let count = icons.count
        label.fontSize = count <= 2 ? 150 : max(30, 320 / CGFloat(count))
        label.verticalAlignmentMode = .center
        label.horizontalAlignmentMode = .center
        let holder = SKNode()
        holder.addChild(label)
        return holder
    }
